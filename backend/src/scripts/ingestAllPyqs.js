/**
 * Ingest All Official GATE Question Papers & Answer Keys
 * Automatically processes all available official GATE PDFs from 2022 through 2025,
 * validates candidates against official master answer keys, and persists them.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import dotenv from 'dotenv';
import { officialPyqImportService } from '../services/pyqExtraction/officialPyqImport.service.js';
import { sourceRegistry } from '../services/gateSources/sourceRegistry.js';
import { connectToDatabase, disconnectDatabase, isDatabaseConnected } from '../config/db.js';
import { MongoQuestionRepository } from '../repositories/MongoQuestionRepository.js';

dotenv.config({ path: 'backend/.env' });

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Standalone in-memory store for running the import
class IngestStore {
  constructor() {
    this.questions = new Map();
  }
  findById(id) {
    return this.questions.get(id) || null;
  }
  findAll() {
    return Array.from(this.questions.values());
  }
  create(q) {
    this.questions.set(q.id, { ...q });
    return q;
  }
  count() {
    return this.questions.size;
  }
}

async function runIngestion() {
  console.log('====================================================');
  console.log('🚀 GATEForge: Official PYQ Ingestion Pipeline');
  console.log('====================================================\n');

  // 1. Initialize store
  const memStore = new IngestStore();
  let mongoRepo = null;

  const mongoUri = process.env.MONGODB_URI;
  if (mongoUri) {
    const connected = await connectToDatabase(mongoUri);
    if (connected) {
      console.log('✅ Connected to MongoDB for persistent storage.');
      mongoRepo = new MongoQuestionRepository();
    } else {
      console.log('ℹ️  MongoDB connection not established. Operating in standalone JSON mode.');
    }
  } else {
    console.log('ℹ️  No MONGODB_URI configured. Operating in standalone JSON mode.');
  }

  // Pure synchronous memory store during extraction
  const activeStore = {
    findById: (id) => memStore.findById(id),
    findAll: () => memStore.findAll(),
    create: (q) => memStore.create(q),
  };

  const sourcesToIngest = [
    { id: 'gate-2022-cs-paper', name: 'GATE 2022 CS' },
    { id: 'gate-2023-cs-paper', name: 'GATE 2023 CS' },
    { id: 'gate-2024-cs-paper', name: 'GATE 2024 CS (Session 1)' },
    { id: 'gate-2024-cs2-paper', name: 'GATE 2024 CS (Session 2)' },
    { id: 'gate-2025-cs1-paper', name: 'GATE 2025 CS (Session 1)' },
    { id: 'gate-2025-cs2-paper', name: 'GATE 2025 CS (Session 2)' },
  ];

  const summary = [];

  for (const src of sourcesToIngest) {
    console.log(`\n⏳ Ingesting ${src.name} (${src.id})...`);
    try {
      const report = await officialPyqImportService.importOfficialPyqs(src.id, activeStore);
      console.log(`  ✅ Successfully processed:`);
      console.log(`     • Total Candidates : ${report.totalCandidates}`);
      console.log(`     • Validated        : ${report.validCandidates}`);
      console.log(`     • Imported to Store: ${report.imported}`);
      console.log(`     • Needs Review     : ${report.needsReview}`);
      console.log(`     • Duplicates       : ${report.duplicates}`);

      summary.push({
        paper: src.name,
        sourceId: src.id,
        total: report.totalCandidates,
        valid: report.validCandidates,
        imported: report.imported,
        needsReview: report.needsReview,
        status: 'SUCCESS',
      });
    } catch (err) {
      console.error(`  ❌ Failed to ingest ${src.name}: ${err.message}`);
      summary.push({
        paper: src.name,
        sourceId: src.id,
        error: err.message,
        status: 'FAILED',
      });
    }
  }

  // Export to JSON data file
  const allQuestions = memStore.findAll();
  const outputPath = path.resolve(__dirname, '../data/officialImportedPyqs.json');
  fs.writeFileSync(outputPath, JSON.stringify(allQuestions, null, 2), 'utf8');
  console.log(`\n💾 Saved ${allQuestions.length} official questions to: ${outputPath}`);

  // Also export as JS module for fast native ESM imports
  const jsOutputPath = path.resolve(__dirname, '../data/officialImportedPyqs.js');
  const jsContent = `/**
 * Official Imported GATE Previous-Year Questions (Auto-generated by Ingestion Pipeline)
 * Total Questions: ${allQuestions.length}
 */

export const OFFICIAL_IMPORTED_PYQS = ${JSON.stringify(allQuestions, null, 2)};
`;
  fs.writeFileSync(jsOutputPath, jsContent, 'utf8');
  console.log(`💾 Saved JS module to: ${jsOutputPath}`);

  console.log('\n====================================================');
  console.log('📊 INGESTION SUMMARY');
  console.log('====================================================');
  console.table(summary);
  console.log(`\n🎉 Grand Total Valid Authentic GATE Questions: ${allQuestions.length}`);

  // If MongoDB is connected, persist records safely
  if (mongoRepo && isDatabaseConnected()) {
    console.log(`\n🔄 Persisting ${allQuestions.length} questions into MongoDB...`);
    let newMongoCount = 0;
    let existingMongoCount = 0;
    for (const q of allQuestions) {
      try {
        const existing = await mongoRepo.findById(q.id);
        if (!existing) {
          await mongoRepo.create(q);
          newMongoCount++;
        } else {
          existingMongoCount++;
        }
      } catch (err) {
        console.warn(`[Mongo Write Error] Failed for ${q.id}: ${err.message}`);
      }
    }
    console.log(`✅ MongoDB sync complete: ${newMongoCount} inserted, ${existingMongoCount} already existed.`);
    const totalInDb = await mongoRepo.count();
    console.log(`📊 Total questions now in MongoDB: ${totalInDb}`);
    await disconnectDatabase();
  }
}

runIngestion().catch((err) => {
  console.error('Fatal ingestion error:', err);
  process.exit(1);
});
